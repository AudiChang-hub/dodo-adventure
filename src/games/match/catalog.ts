export interface MatchPic {
  /** 也是圖示名（Fluent Emoji Flat） */
  id: string
  en: string
  zh: string
  theme: MatchThemeId
  /** 輪廓認得出來：影子配對用得到 */
  shadow: boolean
  /** 輪廓很像的一組（沒有：null） */
  look: string | null
}

export const MATCH_PICS: MatchPic[] = (Object.keys(ROWS) as MatchThemeId[]).flatMap((theme) =>
  ROWS[theme]
    .filter((r) => r[1])
    .map(([icon, en, zh, tags = '']) => {
      const t = tags.split(/\s+/)
      const look = t.find((x) => x.startsWith('='))
      return { id: icon, en, zh, theme, shadow: t.includes('s'), look: look ? look.slice(1) : null }
    }),
)

export const matchPic = (id: string) => MATCH_PICS.find((p) => p.id === id) ?? null
export const themeName = (id: MatchThemeId) => MATCH_THEMES.find((t) => t.id === id)?.zh ?? id
