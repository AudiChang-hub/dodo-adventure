/** 正 n 邊形的星星（尖角 r、內角 r2） */
const star = (cx: number, cy: number, r: number, r2: number, n = 5) =>
  Array.from({ length: n * 2 }, (_, i) => {
    const a = (i / (n * 2)) * Math.PI * 2 - Math.PI / 2
    const rr = i % 2 ? r2 : r
    return `${i ? 'L' : 'M'}${Math.round(cx + Math.cos(a) * rr)} ${Math.round(cy + Math.sin(a) * rr)}`
  }).join(' ') + ' Z'

